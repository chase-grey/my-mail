/**
 * Generates every app icon in public/icons from the one drawing below.
 * Run with `npm run icons` after changing anything here.
 *
 * The manifest needs PNGs, not just SVG: Chrome on Android only builds a real
 * installed app (and only offers to install) from raster manifest icons, and
 * with an SVG alone the home screen gets Chrome's generated letter tile. iOS
 * reads only the PNG behind `<link rel="apple-touch-icon">`.
 *
 * There is no image library in this project, and the drawing is a rounded
 * rectangle and two lines, so the rasterizer is a distance field and the PNG
 * encoder is node's own zlib.
 *
 * The icon has no background, like workout-tracker's and my-brain's: every
 * output is the bare envelope on transparent pixels. That also means there is
 * no maskable variant, since a maskable icon has to be opaque edge to edge.
 */
import { deflateSync } from 'node:zlib'
import { mkdir, writeFile } from 'node:fs/promises'
import path from 'node:path'
import { fileURLToPath } from 'node:url'

const OUT = path.join(path.dirname(fileURLToPath(import.meta.url)), '..', 'public', 'icons')

// --- the drawing ---------------------------------------------------------

const SIZE = 512 // design space; every output is a scaling of this
const FG = [0xff, 0xff, 0xff]
// The browser tab is the one place the icon can follow its surroundings: an SVG
// can ask for the colour scheme, so it turns dark on a light tab strip.
const FG_ON_LIGHT = [0x10, 0x11, 0x14]

// An envelope outline: a rounded rectangle and the flap as a V.
const STROKE = 16
const BODY = { x: 60, y: 122, width: 392, height: 268, radius: 34 }
const FLAP = [
  [76, 144],
  [256, 284],
  [436, 144],
]

// --- SVG -----------------------------------------------------------------

const hex = ([r, g, b]) => `#${[r, g, b].map((c) => c.toString(16).padStart(2, '0')).join('')}`

function svg() {
  const { x, y, width, height } = BODY
  return `<!-- Generated by scripts/make-icons.mjs. Edit that, not this. -->
<svg xmlns="http://www.w3.org/2000/svg" width="${SIZE}" height="${SIZE}" viewBox="0 0 ${SIZE} ${SIZE}">
  <style>@media (prefers-color-scheme: light) { g { stroke: ${hex(FG_ON_LIGHT)} } }</style>
  <g fill="none" stroke="${hex(FG)}" stroke-width="${STROKE}" stroke-linecap="round" stroke-linejoin="round">
    <rect x="${x}" y="${y}" width="${width}" height="${height}" rx="${BODY.radius}"/>
    <polyline points="${FLAP.map((point) => point.join(',')).join(' ')}"/>
  </g>
</svg>
`
}

// --- raster --------------------------------------------------------------

const clamp01 = (n) => (n < 0 ? 0 : n > 1 ? 1 : n)

/** Signed distance to a rounded rectangle: negative inside. */
function distToRoundedRect(px, py, { x, y, width, height, radius }) {
  const qx = Math.abs(px - (x + width / 2)) - (width / 2 - radius)
  const qy = Math.abs(py - (y + height / 2)) - (height / 2 - radius)
  return Math.hypot(Math.max(qx, 0), Math.max(qy, 0)) + Math.min(Math.max(qx, qy), 0) - radius
}

function distToSegment(px, py, [x1, y1], [x2, y2]) {
  const dx = x2 - x1
  const dy = y2 - y1
  const t = clamp01(((px - x1) * dx + (py - y1) * dy) / (dx * dx + dy * dy))
  return Math.hypot(px - (x1 + t * dx), py - (y1 + t * dy))
}

/** RGBA pixels at `size`. A pixel centred on an edge is half covered, which is the antialiasing. */
function raster(size) {
  const unit = SIZE / size // design units per output pixel
  const pixels = Buffer.alloc(size * size * 4)
  for (let y = 0; y < size; y++) {
    for (let x = 0; x < size; x++) {
      const sx = (x + 0.5) * unit
      const sy = (y + 0.5) * unit

      const nearest = Math.min(
        Math.abs(distToRoundedRect(sx, sy, BODY)),
        distToSegment(sx, sy, FLAP[0], FLAP[1]),
        distToSegment(sx, sy, FLAP[1], FLAP[2]),
      )
      const ink = clamp01(0.5 + (STROKE / 2 - nearest) / unit)

      // Colour stays solid and the edge lives in alpha, so no fringe shows on any ground.
      const i = (y * size + x) * 4
      for (let c = 0; c < 3; c++) pixels[i + c] = FG[c]
      pixels[i + 3] = Math.round(ink * 255)
    }
  }
  return pixels
}

// --- PNG -----------------------------------------------------------------

const CRC_TABLE = Uint32Array.from({ length: 256 }, (_, n) => {
  let c = n
  for (let k = 0; k < 8; k++) c = c & 1 ? 0xedb88320 ^ (c >>> 1) : c >>> 1
  return c >>> 0
})

function crc32(buf) {
  let c = 0xffffffff
  for (const byte of buf) c = CRC_TABLE[(c ^ byte) & 0xff] ^ (c >>> 8)
  return (c ^ 0xffffffff) >>> 0
}

function chunk(type, data) {
  const head = Buffer.alloc(8)
  head.writeUInt32BE(data.length, 0)
  head.write(type, 4, 'ascii')
  const crc = Buffer.alloc(4)
  crc.writeUInt32BE(crc32(Buffer.concat([head.subarray(4), data])), 0)
  return Buffer.concat([head, data, crc])
}

/** 8-bit RGBA PNG, filter type 0 on every scanline. */
function png(size, pixels) {
  const stride = size * 4
  const raw = Buffer.alloc((stride + 1) * size)
  for (let y = 0; y < size; y++) {
    pixels.copy(raw, y * (stride + 1) + 1, y * stride, (y + 1) * stride)
  }
  const ihdr = Buffer.alloc(13)
  ihdr.writeUInt32BE(size, 0)
  ihdr.writeUInt32BE(size, 4)
  ihdr[8] = 8 // bit depth
  ihdr[9] = 6 // colour type: truecolour with alpha
  return Buffer.concat([
    Buffer.from([0x89, 0x50, 0x4e, 0x47, 0x0d, 0x0a, 0x1a, 0x0a]),
    chunk('IHDR', ihdr),
    chunk('IDAT', deflateSync(raw, { level: 9 })),
    chunk('IEND', Buffer.alloc(0)),
  ])
}

// --- outputs -------------------------------------------------------------

const FILES = [
  ['app-icon.svg', svg()],
  // What actually gets installed. Chrome on Android reads 192 and 512 from the
  // manifest; iOS reads only apple-touch-icon.png.
  ['apple-touch-icon.png', png(180, raster(180))],
  ['icon-192.png', png(192, raster(192))],
  ['icon-512.png', png(512, raster(512))],
]

await mkdir(OUT, { recursive: true })
for (const [name, data] of FILES) {
  await writeFile(path.join(OUT, name), data)
  console.log(`  public/icons/${name}`)
}
